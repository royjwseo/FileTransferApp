param([string]$OutputDirectory)
$ErrorActionPreference='Stop'
. "$PSScriptRoot/ReleaseCommon.ps1"
$version=Get-ReleaseVersion
if(!$OutputDirectory){$OutputDirectory=Join-Path $RepositoryRoot 'dist'}
$OutputDirectory=[IO.Path]::GetFullPath($OutputDirectory)
$exe=Join-Path $RepositoryRoot 'FileTransferApp/x64/Release/FileTransferAppGui.exe'
foreach($required in @($exe,"$RepositoryRoot/packaging/README.txt","$RepositoryRoot/packaging/LICENSE.txt")){
 if(!(Test-Path -LiteralPath $required -PathType Leaf)){throw "Required release file missing: $required"}
}
$info=[Diagnostics.FileVersionInfo]::GetVersionInfo($exe)
if($info.ProductVersion -ne $version -or $info.IsDebug){throw "Expected non-Debug GUI $version; found $($info.ProductVersion), Debug=$($info.IsDebug). Build Release x64 first."}
$bytes=[IO.File]::ReadAllBytes($exe)
$pe=[BitConverter]::ToInt32($bytes,0x3c)
if([BitConverter]::ToUInt32($bytes,$pe) -ne 0x4550 -or [BitConverter]::ToUInt16($bytes,$pe+4) -ne 0x8664 -or [BitConverter]::ToUInt16($bytes,$pe+24) -ne 0x20b -or [BitConverter]::ToUInt16($bytes,$pe+24+68) -ne 2){throw 'Expected a native Windows GUI x64 PE executable.'}
$inputs=Get-ChildItem "$RepositoryRoot/FileTransferApp/src","$RepositoryRoot/FileTransferApp/include","$RepositoryRoot/FileTransferApp/resources" -File -Recurse
$inputs+=Get-Item "$RepositoryRoot/FileTransferApp/FileTransferAppGui.vcxproj"
if(@($inputs | Where-Object LastWriteTimeUtc -gt (Get-Item $exe).LastWriteTimeUtc).Count){throw 'GUI build is older than source inputs. Rebuild Release x64 before packaging.'}
New-Item -ItemType Directory -Force $OutputDirectory | Out-Null
$name="FileTransferApp-v$version-win-x64"
$stage=Join-Path $OutputDirectory ('.staging-'+[Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $stage | Out-Null
Copy-Item -LiteralPath $exe -Destination (Join-Path $stage 'FileTransferAppGui.exe')
$readme=[IO.File]::ReadAllText("$RepositoryRoot/packaging/README.txt").Replace('{{VERSION}}',$version)
[IO.File]::WriteAllText((Join-Path $stage 'README.txt'),$readme,[Text.UTF8Encoding]::new($true))
Copy-Item -LiteralPath "$RepositoryRoot/packaging/LICENSE.txt" -Destination (Join-Path $stage 'LICENSE.txt')
Add-Type -AssemblyName System.IO.Compression
$temporary=Join-Path $OutputDirectory ('.package-'+[Guid]::NewGuid().ToString('N')+'.zip')
$stream=[IO.File]::Open($temporary,[IO.FileMode]::CreateNew)
$archive=[IO.Compression.ZipArchive]::new($stream,[IO.Compression.ZipArchiveMode]::Create,$false)
try {
 foreach($file in @(Get-ChildItem -LiteralPath $stage -File | Sort-Object Name)){
  $entry=$archive.CreateEntry("$name/$($file.Name)",[IO.Compression.CompressionLevel]::Optimal)
  $entry.LastWriteTime=[DateTimeOffset]::new(1980,1,1,0,0,0,[TimeSpan]::Zero)
  $output=$entry.Open();$input=[IO.File]::OpenRead($file.FullName)
  try{$input.CopyTo($output)}finally{$input.Dispose();$output.Dispose()}
 }
} finally {$archive.Dispose();$stream.Dispose()}
$zip=Join-Path $OutputDirectory "$name.zip"
$hash=(Get-FileHash -LiteralPath $temporary -Algorithm SHA256).Hash.ToLowerInvariant()
if(Test-Path -LiteralPath $zip){
 if((Get-FileHash -LiteralPath $zip).Hash.ToLowerInvariant() -ne $hash){throw "Existing package differs; refusing to overwrite: $zip. Use a new output directory or version. Candidate retained: $temporary"}
 # Delete only the identical temporary ZIP generated by this invocation.
 Remove-Item -LiteralPath $temporary
}else{Move-Item -LiteralPath $temporary -Destination $zip}
$line="$hash  $name.zip"+[char]10
$checksums=Join-Path $OutputDirectory 'SHA256SUMS.txt'
if(Test-Path -LiteralPath $checksums){
 if([IO.File]::ReadAllText($checksums) -ne $line){throw "Existing checksum file differs; refusing to overwrite: $checksums"}
}else{[IO.File]::WriteAllText($checksums,$line,[Text.UTF8Encoding]::new($false))}
Write-Output "Package: $zip"
Write-Output "SHA256: $hash"
Write-Output "Staging retained for inspection: $stage"
